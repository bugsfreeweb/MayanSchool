import { chromium } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] });
await mkdir('test-artifacts', { recursive: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
await page.goto('http://localhost:3000', { waitUntil: 'networkidle' });
await page.evaluate(() => document.fonts.ready);
await page.screenshot({ path: 'test-artifacts/home-desktop.png', fullPage: true });
console.log('DESKTOP', await page.evaluate(() => ({ title: document.title, width: window.innerWidth, scrollWidth: document.documentElement.scrollWidth, height: document.documentElement.scrollHeight, cardCount: document.querySelectorAll('.game-card').length, hero: document.querySelector('.hero-banner')?.getBoundingClientRect().toJSON() })));
await page.setViewportSize({ width: 390, height: 844 });
await page.waitForTimeout(400);
await page.screenshot({ path: 'test-artifacts/home-mobile.png', fullPage: true });
console.log('MOBILE', await page.evaluate(() => ({ width: window.innerWidth, scrollWidth: document.documentElement.scrollWidth, height: document.documentElement.scrollHeight })));
await page.setViewportSize({ width: 1440, height: 1000 });
await page.goto('http://localhost:3000/games', { waitUntil: 'networkidle' });
await page.screenshot({ path: 'test-artifacts/library-desktop.png', fullPage: true });
console.log('BROWSER_ERRORS', JSON.stringify(errors));
await browser.close();
